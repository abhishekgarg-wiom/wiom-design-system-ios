"""Generate skills-ios/wiom-ios-foundations/references/tokens.json from tokens.md.

tokens.md is the source of truth; never edit tokens.json by hand. Run from
the repo root after changing tokens.md:

    python3 scripts/build_tokens_json.py

Standard library only.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent)
REF = ROOT / "skills-ios/wiom-ios-foundations/references"
SRC = REF / "tokens.md"
OUT = REF / "tokens.json"

GROUPS = {  # section heading prefix -> (json key, Swift namespace)
    "## 3. Spacing": ("spacing", "Wiom.Spacing"),
    "## 4. Radius": ("radius", "Wiom.Radius"),
    "## 5. Border width": ("borderWidth", "Wiom.BorderWidth"),
    "## 6. Shadow": ("shadow", "Wiom.Shadow"),
    "## 7. Icon size": ("iconSize", "Wiom.IconSize"),
}


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def unquote(s):
    return s.strip().strip("`")


def main():
    data = {
        "source": "skills-ios/wiom-ios-foundations/references/tokens.md",
        "note": "Generated by scripts/build_tokens_json.py. Edit tokens.md, then regenerate.",
        "colors": [],
        "spacing": [],
        "radius": [],
        "borderWidth": [],
        "shadow": [],
        "iconSize": [],
        "overlay": [],
    }
    section = None
    subgroup = None
    for line in SRC.read_text().split("\n"):
        if line.startswith("## "):
            section = next((v for k, v in GROUPS.items() if line.startswith(k)), None)
            if line.startswith("## 2. Semantic colours"):
                section = ("colors", "Wiom.Colors")
            if line.startswith("## 8. Opacity"):
                section = ("overlay", "Wiom.Colors")
            subgroup = None
            continue
        if line.startswith("### "):
            subgroup = re.sub(r"^### [\d.]+\s*", "", line).strip()
            continue
        if not section or not line.startswith("| `"):
            continue
        c = cells(line)
        key, ns = section
        m0 = re.match(r"`([^`]+)`", c[0])
        name = m0.group(1) if m0 else unquote(c[0])
        if key == "colors":
            if len(c) < 4:
                continue
            m = re.match(r"(#[0-9A-Fa-f]{6})\s*←\s*(.+)", c[2])
            if not m:
                continue
            data["colors"].append({
                "name": name, "group": subgroup, "swift": f"{ns}.{unquote(c[1])}",
                "hex": m.group(1).upper(), "primitive": m.group(2).strip(), "usage": c[3],
            })
        elif key == "overlay":
            data["overlay"].append({"name": name, "swift": "Wiom.Colors.overlayScrim", "value": c[1], "usage": c[2]})
        elif key == "shadow":
            data["shadow"].append({"name": name, "swift": f"{ns}{unquote(c[1])}" if unquote(c[1]).startswith(".") else unquote(c[1]),
                                   "css": c[2], "swiftui": unquote(c[3])})
        else:
            swift = unquote(c[1])
            if not swift.startswith("Wiom."):
                swift = f"{ns}.{swift}"
            value = c[2].replace("*", "")
            entry = {"name": name, "swift": swift, "pt": int(value) if value.isdigit() else value, "usage": c[3]}
            data[key].append(entry)
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print(f"tokens.json: {len(data['colors'])} colours, {len(data['spacing'])} spacing, "
          f"{len(data['radius'])} radius, {len(data['borderWidth'])} widths, "
          f"{len(data['shadow'])} shadows, {len(data['iconSize'])} icon sizes")


if __name__ == "__main__":
    main()
